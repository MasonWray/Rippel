/**
 * Custom widgets: LVGL widgets written in C by the user, declared in the
 * contract and used in TSX like any element.
 *
 * Rippel never sees the widget's code. It declares a C interface for it, one
 * create function and one setter per prop, which the user implements. The
 * device build calls those functions. The dev server compiles the same C into
 * the simulator when Emscripten is available.
 */
import { readFileSync } from "node:fs";
import { parseSync, type types as t } from "@babel/core";

export interface WidgetValue {
  base: "int" | "float" | "bool" | "string";
  ctype: string;
  unsigned?: boolean;
  maxLength?: number;
}

export interface CustomWidget {
  /** Name in the contract, like `PressureDial`. */
  jsName: string;
  /** C name, like `pressure_dial`. */
  name: string;
  props: { jsName: string; name: string; value: WidgetValue }[];
}

export const WIDGET_TYPES: Record<string, WidgetValue> = {
  i8: { base: "int", ctype: "int8_t" },
  u8: { base: "int", ctype: "uint8_t", unsigned: true },
  i16: { base: "int", ctype: "int16_t" },
  u16: { base: "int", ctype: "uint16_t", unsigned: true },
  i32: { base: "int", ctype: "int32_t" },
  u32: { base: "int", ctype: "uint32_t", unsigned: true },
  f32: { base: "float", ctype: "float" },
  bool: { base: "bool", ctype: "bool" },
};

/** Props every element has, which a custom widget can't redefine. */
const RESERVED = new Set(["class", "style", "id", "hidden", "disabled", "checked", "children", "ref"]);

/** `PressureDial` -> `pressure_dial`. */
export function widgetCName(jsName: string): string {
  return jsName.replace(/[A-Z]/g, (c, i: number) => (i ? "_" : "") + c.toLowerCase());
}

export const widgetCreate = (w: CustomWidget) => `ui_widget_${w.name}_create`;
export const widgetSetter = (w: CustomWidget, prop: string) => `ui_widget_${w.name}_set_${prop}`;

const paramType = (v: WidgetValue) => (v.base === "string" ? "const char *" : v.ctype);

/** Reads `export const X = widget({ ... })` declarations from a contract file. */
export function contractWidgets(file: string): CustomWidget[] {
  const ast = parseSync(readFileSync(file, "utf8"), {
    filename: file,
    babelrc: false,
    configFile: false,
    sourceType: "module",
    parserOpts: { plugins: ["typescript"] },
  });
  const widgets: CustomWidget[] = [];
  for (const statement of ast?.program.body ?? []) {
    if (statement.type !== "ExportNamedDeclaration" || statement.declaration?.type !== "VariableDeclaration") continue;
    for (const decl of statement.declaration.declarations) {
      const init = decl.init;
      if (decl.id.type !== "Identifier" || init?.type !== "CallExpression" || init.callee.type !== "Identifier" || init.callee.name !== "widget") continue;
      const shape = init.arguments[0];
      if (shape?.type !== "ObjectExpression") throw new Error(`${file}: widget() takes an object of prop types`);
      widgets.push(widgetFromShape(decl.id.name, shape, file));
    }
  }
  return widgets;
}

export function widgetFromShape(jsName: string, shape: t.ObjectExpression, file: string): CustomWidget {
  const props = shape.properties.map((p) => {
    if (p.type !== "ObjectProperty" || p.key.type !== "Identifier") throw new Error(`${file}: expected \`name: type\` in widget ${jsName}`);
    if (RESERVED.has(p.key.name) || /^on[A-Z]/.test(p.key.name)) {
      throw new Error(`${file}: ${jsName}.${p.key.name} clashes with a prop every element has. Pick another name.`);
    }
    return { jsName: p.key.name, name: widgetCName(p.key.name), value: widgetType(p.value, `${jsName}.${p.key.name}`, file) };
  });
  return { jsName, name: widgetCName(jsName), props };
}

function widgetType(node: t.Node, where: string, file: string): WidgetValue {
  if (node.type === "Identifier" && WIDGET_TYPES[node.name]) return WIDGET_TYPES[node.name];
  if (node.type === "CallExpression" && node.callee.type === "Identifier" && node.callee.name === "str" && node.arguments[0]?.type === "NumericLiteral") {
    return { base: "string", ctype: "char", maxLength: node.arguments[0].value };
  }
  throw new Error(`${file}: ${where} needs a contract type like u8, f32, bool or str(32)`);
}

/** The C interface the user implements: ui_widgets.h. */
export function widgetHeader(widgets: CustomWidget[]): string {
  const lines = [
    "/* GENERATED BY RIPPEL. DO NOT EDIT. */",
    "/* Custom widgets declared in the firmware contract. Implement these functions in your own C files. */",
    "#ifndef UI_WIDGETS_H",
    "#define UI_WIDGETS_H",
    "",
    '#include "lvgl.h"',
    "#include <stdbool.h>",
    "#include <stdint.h>",
    "",
    "#ifdef __cplusplus",
    'extern "C" {',
    "#endif",
  ];
  for (const w of widgets) {
    lines.push("", `/* <${w.jsName}>: create the widget under \`parent\` and return it. */`, `lv_obj_t * ${widgetCreate(w)}(lv_obj_t * parent);`);
    for (const p of w.props) lines.push(`void ${widgetSetter(w, p.name)}(lv_obj_t * obj, ${paramType(p.value)} value);`);
  }
  lines.push("", "#ifdef __cplusplus", "}", "#endif", "", "#endif /* UI_WIDGETS_H */", "");
  return lines.join("\n");
}

/** Emscripten names of every widget function, for EXPORTED_FUNCTIONS. */
export function widgetExports(widgets: CustomWidget[]): string[] {
  return widgets.flatMap((w) => [`_${widgetCreate(w)}`, ...w.props.map((p) => `_${widgetSetter(w, p.name)}`)]);
}
